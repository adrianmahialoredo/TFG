package com.demo.demo.model;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import lombok.*;
import java.util.*;

/**
 * Represents a musical song in the system.
 * 
 * The Song entity is used to store information about various songs, including their title,
 * artist, and associated genres and instruments. It supports a one-to-many relationship with
 * the Lesson entity, meaning that a song can have multiple lessons associated with it.
 * 
 * Additionally, it supports many-to-many relationships with both the Genre and Instrument entities,
 * meaning that many songs can belong to many genres and many instruments can be featured in many songs.
 * 
 * This class is annotated with JPA annotations to map it to a database table,
 * and it uses Lombok annotations to reduce boilerplate code for getters, setters,
 * constructors, and other common methods.
 * 
 * @author Adrián Mahía
 * @version 1.0
 * @since 2025-06-06
 */
@Entity
@Table(name = "songs")
@DiscriminatorValue("SONG")
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class Song extends Item {

    /**
     * Unique identifier for the song.
     * This field is automatically generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Title of the song.
     * This field is required and cannot be blank.
     */
    @Column(nullable = false)
    @NotBlank
    private String title;

    /**
     * Artist of the song.
     * This field is required and cannot be blank.
     */
    @Column(nullable = false)
    @NotBlank
    private String artist;

    /**
     * Relation with Genre
     * This is a many-to-many relationship, meaning that many songs can belong to many genres.
     * A genre can have multiple songs, and a song can be associated with multiple genres.
     */
    @ManyToMany
    @JoinTable(
        name = "song_genre",
        joinColumns = @JoinColumn(name = "song_id"),
        inverseJoinColumns = @JoinColumn(name = "genre_id")
    )
    private Set<Genre> genres = new HashSet<>();

    /**
     * Relation with Instrument
     * This is a many-to-many relationship, meaning that many songs can feature many instruments.
     * A song can be associated with multiple instruments, and an instrument can be featured in multiple songs.
     */
    @ManyToMany(mappedBy = "songs")
    @JsonIgnore
    private Set<Instrument> instruments = new HashSet<>();

    /**
     * Relation with Lesson
     * This is a one-to-many relationship, meaning that one song can have many lessons.
     * A lesson can be associated with one song, but a song can have multiple lessons.
     */
    @OneToMany(mappedBy = "song", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<SongLesson> lessons = new ArrayList<>();

    /**
     * ToString method to represent the Song object.
     */
    @Override
    public String toString() {
        return "Song{" +
                "id=" + id +
                ", title='" + title + '\'' +
                ", artist='" + artist + '\'' +
                //", description='" + description + '\'' +
                '}';
    }

}

