package com.demo.demo.model;

import jakarta.persistence.*;
import lombok.*;

/**
 * Represents a section of a tab in a song lesson.
 * 
 * This entity is used to store the content of a tab section, which can be identified by an identifier
 * such as "intro", "solo", etc. The content is stored as a large object (LOB) to accommodate multiline text.
 * Each tab section is associated with a specific song lesson.
 * 
 * This class is annotated with JPA annotations to map it to a database table,
 * and it uses Lombok annotations to reduce boilerplate code for getters, setters,
 * constructors, and other common methods.
 * 
 * @author Adrián Mahía
 * @version 1.0
 * @since 2025-06-06
 */
@Entity
@Table(name = "tab_sections")
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class TabSection {
    
    /**
     * Unique identifier for the tab section.
     * This field is automatically generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Identifier for the tab section.
     * This field is used to categorize the section, such as "intro", "solo", etc.
     */
    private String identifier;

    /**
     * Content of the tab section, which is stored as a large object (LOB).
     * The content is expected to be in a multiline format, representing the musical notation for the section.
     * This field is required and cannot be blank.
     */
    @Lob
    private String content; // tab real en multilinea

    /**
     * The song lesson to which this tab section belongs.
     * This is a many-to-one relationship, meaning that many tab sections can belong to the same song lesson.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "song_lesson_id")
    private SongLesson songLesson;

}
