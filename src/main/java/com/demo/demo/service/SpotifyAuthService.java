package com.demo.demo.service;

/**
 * Service contract for the Spotify OAuth2 authorization flow.
 *
 * Builds the authorization URL and handles the callback exchange to link a
 * Spotify account with an application user.
 *
 * @author Adrián Mahía
 * @version 1.0
 * @since 2025-06-06
 */
public interface SpotifyAuthService {

    /**
     * Builds the Spotify authorization URL for an application user.
     *
     * The browser redirect from Spotify to the callback does not carry the JWT of the app,
     * so the user is identified through the OAuth2 {@code state} parameter: a random,
     * single-use value that expires after a few minutes.
     *
     * @param username The username of the authenticated application user linking Spotify.
     * @return The authorization URL as a String.
     */
    String buildAuthorizationUrl(String username);

    /**
     * Manage the callback from Spotify after user authorization.
     *
     * @param code  The authorization code received from Spotify.
     * @param state The {@code state} generated by {@link #buildAuthorizationUrl(String)}.
     * @throws IllegalArgumentException if the code is empty or the state is unknown or expired.
     */
    void handleCallback(String code, String state);

    /**
     * Returns a valid access token for the Spotify account linked to an application user.
     *
     * If the stored token is expired (or about to expire) it is refreshed first with the
     * refresh token, and the new token is persisted.
     *
     * @param userId the ID of the application user
     * @return a valid Spotify access token
     * @throws jakarta.persistence.EntityNotFoundException if the user has no linked Spotify account.
     * @throws IllegalStateException if Spotify rejects the refresh (e.g. access revoked); the user
     *                               has to link the account again.
     */
    String getValidAccessToken(Long userId);
}
