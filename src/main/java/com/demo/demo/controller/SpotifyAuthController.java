package com.demo.demo.controller;

import com.demo.demo.service.SpotifyAuthService;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.authentication.AnonymousAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.web.bind.annotation.*;

import java.util.Map;
import java.util.Optional;

/**
 * REST controller for the Spotify OAuth2 authentication flow.
 *
 * Base path: {@code /api/spotify}
 *
 * Endpoints:
 * - GET    /api/spotify/login                     Retrieve the Spotify authorization URL for the authenticated user (JWT required)
 * - GET    /api/spotify/callback?code=&state=     Receive the authorization code from Spotify and store the tokens
 *
 * Flow:
 * 1. The app calls {@code /login} with its JWT and opens the returned {@code authUrl} in the browser.
 * 2. Spotify redirects the browser to {@code /callback}. That redirect does not carry the JWT,
 *    so the user is identified through the OAuth2 {@code state} generated in step 1.
 * 3. The callback answers with a small HTML page telling the user to go back to the app.
 *
 * Spotify recommendations live in {@link SpotifyRecommendationController}.
 *
 * Responses: 200 OK, 400 Bad Request (authorization denied, invalid or expired state) and
 * 401 Unauthorized when {@code /login} is called without an authenticated user.
 *
 * @author Adrián Mahía
 * @version 1.0
 * @since 2025-06-06
 */
@RestController
@RequestMapping("/api/spotify")
@RequiredArgsConstructor
public class SpotifyAuthController {

    private final SpotifyAuthService spotifyAuthService;

    /**
     * Retrieves the Spotify authorization URL for the authenticated user.
     *
     * @return 200 OK with {@code {"authUrl": "..."}}, or 401 Unauthorized
     */
    @GetMapping("/login")
    public ResponseEntity<Map<String, String>> getLoginUrl() {
        return currentUsername()
                .map(username -> ResponseEntity.ok(Map.of("authUrl", spotifyAuthService.buildAuthorizationUrl(username))))
                .orElseGet(() -> ResponseEntity.status(HttpStatus.UNAUTHORIZED).build());
    }

    /**
     * Handles the Spotify OAuth2 callback: exchanges the authorization code for tokens
     * and stores them for the user that started the login.
     *
     * @param code  the authorization code sent by Spotify (absent if the user denied access)
     * @param state the state generated by {@link #getLoginUrl()}
     * @param error the error sent by Spotify when the user denied access
     * @return 200 OK with an HTML confirmation page, or 400 Bad Request
     */
    @GetMapping(value = "/callback", produces = MediaType.TEXT_HTML_VALUE)
    public ResponseEntity<String> callback(@RequestParam(required = false) String code,
                                           @RequestParam(required = false) String state,
                                           @RequestParam(required = false) String error) {
        if (error != null) {
            return ResponseEntity.badRequest().body(page("No se ha conectado Spotify (" + error + "). Puedes volver a la app."));
        }
        spotifyAuthService.handleCallback(code, state);
        return ResponseEntity.ok(page("¡Spotify conectado! Ya puedes volver a la app."));
    }

    private static Optional<String> currentUsername() {
        return Optional.ofNullable(SecurityContextHolder.getContext().getAuthentication())
                .filter(Authentication::isAuthenticated)
                .filter(authentication -> !(authentication instanceof AnonymousAuthenticationToken))
                .map(Authentication::getName);
    }

    private static String page(String message) {
        return "<!doctype html><html><head><meta charset=\"utf-8\"><title>Spotify</title></head>"
                + "<body style=\"font-family:sans-serif;text-align:center;padding-top:3rem\"><p>"
                + message.replace("<", "&lt;")
                + "</p></body></html>";
    }
}
