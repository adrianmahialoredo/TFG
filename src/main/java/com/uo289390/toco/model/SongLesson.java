package com.uo289390.toco.model;

import com.fasterxml.jackson.annotation.JsonBackReference;
import com.fasterxml.jackson.annotation.JsonManagedReference;
import java.util.*;
import jakarta.persistence.*;
import jakarta.validation.constraints.*;
import lombok.*;

import com.uo289390.toco.utils.Identifiable;

/**
 * Represents a song lesson in the application.
 * 
 * The SongLesson entity is used to store information about a specific lesson for a song,
 * including its difficulty level, associated chords, lyrics, video URL, tab sections,
 * and relationships with the Song and Instrument entities.
 * 
 * This class is annotated with JPA annotations to map it to a database table,
 * and it uses Lombok annotations to reduce boilerplate code for getters, setters,
 * constructors, and other common methods.
 * 
 * @author Adrián Mahía
 * @version 1.0
 * @since 2025-06-06
 */
@Entity
@Table(name = "song_lessons")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class SongLesson implements Identifiable<Long> {
    
    /**
     * Unique identifier for the song lesson.
     * This field is automatically generated by the database.
     */
    @Id
    private Long id;

    /**
     * Enumerated representing the difficulty of the lesson, which can be EASY, MEDIUM, or ORIGINAL.
     */
    @Enumerated(EnumType.STRING)
    @NotNull(message = "Difficulty level cannot be null")
    private DifficultyLevel difficulty; // EASY, MEDIUM, ORIGINAL

    /**
     * Relation with Chord
     * This is a many-to-many relationship, meaning that many songs can have many chords.
     * A chord can be used in multiple songs, and a song can have multiple chords.
     */
    @ManyToMany
    @JoinTable(
        name = "song_chords",
        joinColumns = @JoinColumn(name = "song_lesson_id"),
        inverseJoinColumns = @JoinColumn(name = "chord_id")
    )
    @OrderBy("id ASC")
    private Set<Chord> chords = new LinkedHashSet<>();
    
    /**
     * Lyrics of the song lesson.
     * This field is required and stored as a large object (LOB) in the database.
     */
    @Lob
    @NotBlank(message = "Chorded lyrics cannot be blank")
    private String chordedLyrics; // format "[chord] lyric line 1\n[chord] lyric line 2\n..."

    /**
     * URL of the video lesson.
     * This field is optional and can be null.
     */
    @Pattern(regexp = "^https?://.+|^$", message = "Video URL must be a valid HTTP/HTTPS URL or empty")
    private String videoUrl;


    /**
     * List of tab sections associated with the song lesson.
     * This is a one-to-many relationship, meaning that one song lesson can have multiple tab sections.
     * A tab section can be associated with one specific song lesson.
     */
    @OneToMany(mappedBy = "songLesson", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonManagedReference(value = "songLesson-tabSections")
    private List<TabSection> tabSections = new ArrayList<>();

    /**
     * Relation with Song
     * This is a many-to-one relationship, meaning that many song lessons can belong to one song.
     * A song can have multiple lessons, but a lesson is associated with one specific song.
     */
    @NotNull(message = "Song cannot be null")
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "song_id")
    @JsonBackReference(value = "song-songLessons")
    private Song song;

    /**
     * Relation with Instrument
     * This is a many-to-one relationship, meaning that many song lessons can be associated with one instrument.
     * A lesson can be tailored for a specific instrument, but multiple lessons can be created for the same instrument.
     */
    @NotNull(message = "Instrument cannot be null")
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "instrument_id")
    private Instrument instrument;

    /**
     * Enum representing the difficulty levels of the song lesson.
     * The levels are EASY, MEDIUM, and ORIGINAL.
     */
    public enum DifficultyLevel {
        EASY, MEDIUM, ORIGINAL;

        /**
         * Parses a difficulty coming from a request.
         *
         * @param value the difficulty name (EASY, MEDIUM or ORIGINAL)
         * @return the matching difficulty
         * @throws IllegalArgumentException if the value is missing or unknown (mapped to a 400)
         */
        public static DifficultyLevel from(String value) {
            if (value == null) {
                throw new IllegalArgumentException("Difficulty is required");
            }
            try {
                return valueOf(value);
            } catch (IllegalArgumentException e) {
                throw new IllegalArgumentException("Difficulty must be EASY, MEDIUM, or ORIGINAL");
            }
        }
    }

    /**
     * Two SongLessons are equal when they have the same id, so collections (e.g. {@link java.util.Set})
     * never hold the same SongLesson twice even if it was loaded in different places or is a Hibernate proxy.
     * Ids are assigned manually before the entity is added to any collection, so the hash is stable.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof SongLesson other)) return false;
        return getId() != null && getId().equals(other.getId());
    }

    @Override
    public int hashCode() {
        return java.util.Objects.hashCode(getId());
    }
}
