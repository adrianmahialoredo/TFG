"""Migrate the legacy ``preferences`` table to the current JPA mapping.

Why this script exists
----------------------
The application originally stored the user's musical preferences in a
``preferences`` table whose primary key was its own ``id`` column and which had
two mandatory text columns (``musical_genre`` and ``preferred_instrument``).

The current :code:`com.uo289390.toco.model.Preferences` entity shares the primary key
with ``users`` through ``@MapsId``, so the table only needs ``user_id`` (primary
key). The favourite genres/instruments live in the ``user_favorite_genres``
and ``user_favorite_instruments`` join tables. The level of the user is
``users.difficulty_level`` (0 to 5): the old ``preferences.difficulty_level``
(0 to 100, never used) was removed from the entity.

Hibernate is configured with ``spring.jpa.hibernate.ddl-auto=update``, which
**never drops or relaxes existing columns**. On databases created with the old
schema the insert generated by Hibernate::

    insert into preferences (user_id) values (?)

fails with::

    ERROR: null value in column "musical_genre" violates not-null constraint

and, since ``Preferences.difficultyLevel`` was removed, with::

    ERROR: null value in column "difficulty_level" violates not-null constraint

This script brings the table in line with the mapping. It is idempotent: it can
be run as many times as needed and does nothing if the schema is already fine.

Usage
-----
    python scripts/migrate_preferences_table.py

Connection settings are read from ``src/main/resources/application.properties``
(and the ``.env`` it imports) and can be overridden with the ``DB_URL`` /
``DB_USER`` / ``DB_PASSWORD`` environment variables. ``DB_URL`` may be a Neon
URL without port and with ``?sslmode=require``.
"""

import os
import re
import sys

import psycopg

from console_utils import configure_console
from env_utils import load_properties

configure_console()

LEGACY_COLUMNS = ('musical_genre', 'preferred_instrument', 'difficulty_level')


def build_dsn() -> str:
    """Build a psycopg DSN from the application properties / env vars."""
    props = load_properties()
    url = os.environ.get('DB_URL', props.get('spring.datasource.url', ''))
    user = os.environ.get('DB_USER', props.get('spring.datasource.username', 'postgres'))
    password = os.environ.get('DB_PASSWORD', props.get('spring.datasource.password', ''))

    # Port and query are optional: Neon gives jdbc:postgresql://host/db?sslmode=require
    match = re.match(r'jdbc:postgresql://([^:/?]+)(?::(\d+))?/([\w-]+)(?:\?(.*))?$', url)
    if not match:
        print(f"✗ Could not parse the datasource URL: '{url}'")
        sys.exit(1)

    host, port, dbname, query = match.groups()
    dsn = f"host={host} port={port or 5432} dbname={dbname} user={user} password={password}"
    sslmode = os.environ.get('DB_SSLMODE') or dict(
        p.split('=', 1) for p in (query or '').split('&') if '=' in p
    ).get('sslmode')
    return dsn + (f" sslmode={sslmode}" if sslmode else "")


def table_exists(cur) -> bool:
    cur.execute(
        "select 1 from information_schema.tables "
        "where table_schema = 'public' and table_name = 'preferences'"
    )
    return cur.fetchone() is not None


def existing_columns(cur) -> set:
    cur.execute(
        "select column_name from information_schema.columns "
        "where table_schema = 'public' and table_name = 'preferences'"
    )
    return {row[0] for row in cur.fetchall()}


def primary_key_columns(cur) -> list:
    cur.execute(
        "select kcu.column_name "
        "from information_schema.table_constraints tc "
        "join information_schema.key_column_usage kcu "
        "  on tc.constraint_name = kcu.constraint_name "
        "where tc.table_schema = 'public' "
        "  and tc.table_name = 'preferences' "
        "  and tc.constraint_type = 'PRIMARY KEY'"
    )
    return [row[0] for row in cur.fetchall()]


def primary_key_name(cur):
    cur.execute(
        "select constraint_name from information_schema.table_constraints "
        "where table_schema = 'public' and table_name = 'preferences' "
        "  and constraint_type = 'PRIMARY KEY'"
    )
    row = cur.fetchone()
    return row[0] if row else None


def migrate(cur) -> None:
    if not table_exists(cur):
        print("• The 'preferences' table does not exist yet; Hibernate will create it. Nothing to do.")
        return

    columns = existing_columns(cur)

    # 1. Drop the legacy mandatory columns that no longer exist in the entity.
    for column in LEGACY_COLUMNS:
        if column in columns:
            cur.execute(f'alter table preferences drop column "{column}"')
            print(f"✓ Dropped legacy column 'preferences.{column}'.")

    # 2. The entity uses @MapsId, so the primary key must be 'user_id'.
    if 'user_id' not in columns:
        cur.execute('alter table preferences add column user_id bigint')
        print("✓ Added missing column 'preferences.user_id'.")
        columns.add('user_id')

    pk_columns = primary_key_columns(cur)
    if pk_columns != ['user_id']:
        if 'id' in columns:
            # Preserve the link before dropping the surrogate key.
            cur.execute('update preferences set user_id = id where user_id is null')

        pk = primary_key_name(cur)
        if pk:
            # The join tables (user_favorite_genres / user_favorite_instruments)
            # have foreign keys backed by this index. Dropping it with CASCADE
            # removes those stale foreign keys too; Hibernate recreates them on
            # startup pointing at the new primary key.
            cur.execute(f'alter table preferences drop constraint "{pk}" cascade')
            print(f"✓ Dropped obsolete primary key '{pk}' (and its dependent foreign keys).")

        if 'id' in columns:
            cur.execute('alter table preferences drop column "id"')
            print("✓ Dropped legacy column 'preferences.id' (the PK is now shared with users).")

        cur.execute('alter table preferences alter column user_id set not null')
        cur.execute('alter table preferences add primary key (user_id)')
        print("✓ Primary key moved to 'preferences.user_id'.")

    # 3. Every existing user must own a preferences row.
    cur.execute(
        "insert into preferences (user_id) "
        "select u.id "
        "from users u "
        "left join preferences p on p.user_id = u.id "
        "where p.user_id is null"
    )
    if cur.rowcount:
        print(f"✓ Created preferences rows for {cur.rowcount} existing user(s).")


def main() -> None:
    dsn = build_dsn()
    try:
        with psycopg.connect(dsn) as cn:
            with cn.cursor() as cur:
                migrate(cur)
            cn.commit()
    except psycopg.OperationalError as e:
        print(f"✗ Cannot connect to the database: {e}")
        sys.exit(1)

    print("\nMigration finished. The 'preferences' table now matches the JPA mapping.")


if __name__ == '__main__':
    main()


